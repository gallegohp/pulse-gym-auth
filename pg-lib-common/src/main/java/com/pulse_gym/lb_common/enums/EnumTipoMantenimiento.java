package com.pulse_gym.lb_common.enums;

public enum EnumTipoMantenimiento {

    /**
     * Indica que el mantenimiento es de tipo preventivo, es decir, se realiza de manera programada para evitar fallas o problemas futuros
     */
    PREVENTIVO,

    /**
     * Indica que el mantenimiento es de tipo correctivo, es decir, se realiza para reparar una falla o problema que ya ha ocurrido
     */
    CORRECTIVO;

    
}